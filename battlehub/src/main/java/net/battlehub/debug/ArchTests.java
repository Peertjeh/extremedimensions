/**
 * The citadel lobby in the real game: generated by the architecture engine, every block of its catalog known to
 * this version, placed as planned, walkable from the spawn to every landmark, and pictures of it (and of example
 * buildings) in the log.
 */
final class ArchTests {
	private ArchTests() {}

	static void all(MinecraftServer server, Script s) {
		String tag = "architecture";
		s.waitFor(tag + ": the lobby is built", 400, HubWorld::ready);
		s.check(tag + ": the lobby came from the engine and passed its validation", () -> {
			Lobby.Result r = ArchLobby.last();
			Report rep = ArchLobby.lastReport();
			if (r == null || rep == null) return false;
			BattleHub.LOGGER.info("SELFTEST architecture: {} buildings ({} houses), {} blocks, report {}", r.buildings.size(), r.houses, r.voxels.size(), rep);
			for (Report.Issue i : rep.issues) BattleHub.LOGGER.info("SELFTEST architecture issue: {}", i);
			return rep.ok() && r.landmarks.size() == 4 && r.houses >= 30;
		});
		s.check(tag + ": every block in the engine's catalog exists in this version", () -> {
			List<String> missing = ArchLobby.missingBlocks();
			if (!missing.isEmpty()) BattleHub.LOGGER.warn("SELFTEST architecture: missing catalog blocks {}", missing);
			return missing.isEmpty();
		});
		s.check(tag + ": the placed lobby matches the plan", () -> {
			Lobby.Result r = ArchLobby.last();
			ServerLevel hub = HubWorld.level(server);
			int y0 = HubWorld.floorY();
			int[] counts = {0, 0};
			StringBuilder first = new StringBuilder();
			r.voxels.forEach((x, y, z, id) -> {
				if (((x * 31 + z * 17 + y * 7) & 63) != 0) return;
				counts[0]++;
				BlockState st = hub.getBlockState(new BlockPos(x, y0 + y, z));
				String placed = BuiltInRegistries.BLOCK.getKey(st.getBlock()).getPath();
				String want = net.battlehub.arch.Props.base(id);
				if (!placed.equals(want)) {
					counts[1]++;
					if (first.length() < 300) first.append(x).append(',').append(y).append(',').append(z).append(' ').append(want).append("≠").append(placed).append("; ");
				}
			});
			BattleHub.LOGGER.info("SELFTEST architecture: {} sampled blocks, {} differ {}", counts[0], counts[1], first);
			return counts[0] > 1000 && counts[1] <= counts[0] / 100;
		});
		s.check(tag + ": in the real world, from the spawn on foot to every landmark", () -> {
			Lobby.Result r = ArchLobby.last();
			ServerLevel hub = HubWorld.level(server);
			int y0 = HubWorld.floorY();
			GridPath.Terrain t = terrain(hub);
			int sy = standY(t, 0, y0 + 1, 9);
			boolean ok = sy != Integer.MIN_VALUE;
			for (Map.Entry<String, Attachment> e : Lobby.entrances(r).entrySet()) {
				Attachment a = e.getValue();
				int gy = standY(t, a.x(), y0 + a.y(), a.z());
				List<GridPath.Node> path = gy == Integer.MIN_VALUE || !ok ? null
						: GridPath.find(t, new GridPath.Node(0, sy, 9), new GridPath.Node(a.x(), gy, a.z()), 2.5, 400000);
				BattleHub.LOGGER.info("SELFTEST architecture: way to the {}: {}", e.getKey(), path == null ? "none" : path.size() + " steps");
				ok &= path != null;
			}
			return ok;
		});
		s.check(tag + ": example buildings of every archetype pass their checks", () -> {
			boolean ok = true;
			Library lib = Library.defaults();
			for (var a : Architect.all()) {
				for (long seed = 1; seed <= 2; seed++) {
					Brief br = Architect.brief(a.id(), seed, Regions.dimension(), 1.0);
					Building b = Architect.build(br, lib, Xform.ID, null);
					Report rep = Validator.building(b);
					if (!rep.ok()) {
						BattleHub.LOGGER.warn("SELFTEST architecture: {} seed {}: {}", a.id(), seed, rep.errors());
						ok = false;
					}
				}
			}
			return ok;
		});
		s.run(tag + ": pictures of the lobby and example buildings for the log", () -> {
			Lobby.Result r = ArchLobby.last();
			if (r == null) return;
			Render rd = new Render(r.voxels);
			Preview.log("citadel_overview", rd.view(0, 32, 0.55, 960, 600));
			Preview.log("citadel_from_south_east", rd.view(135, 30, 0.6, 960, 600));
			Preview.log("citadel_spawn_view", rd.perspective(new double[] {0.5, 9, 26}, new double[] {0.5, 16, -80}, 70, 960, 600));
			Library lib = Library.defaults();
			String[][] examples = {{"cathedral", "2"}, {"castle", "7"}, {"mage_tower", "9"}, {"temple_ruin", "6"}};
			for (String[] ex : examples) {
				Brief br = Architect.brief(ex[0], Long.parseLong(ex[1]), Regions.dimension(), 1.0);
				Building b = Architect.build(br, lib, Xform.ID, null);
				Voxels v = new Voxels();
				for (int x = b.plan.minX() - 6; x <= b.plan.maxX() + 6; x++) {
					for (int z = b.plan.minZ() - 6; z <= b.plan.maxZ() + 6; z++) v.set(x, b.floorY - 1, z, "grass_block");
				}
				b.emit(v);
				Connect.apply(v);
				int[] box = {b.plan.minX(), b.plan.minY(), b.plan.minZ(), b.plan.maxX(), b.plan.maxY(), b.plan.maxZ()};
				Preview.log("arch_" + ex[0] + "_" + ex[1], new Render(v).view(30, 20, 0.8, 720, 480, box));
			}
		});
	}

	/** Walking in the real world: through blocks without collision (and doors), standing on blocks no taller than one. */
	static GridPath.Terrain terrain(ServerLevel level) {
		return new GridPath.Terrain() {
			@Override
			public boolean open(int x, int y, int z) {
				BlockPos p = new BlockPos(x, y, z);
				BlockState st = level.getBlockState(p);
				return st.getCollisionShape(level, p).isEmpty() || st.getBlock() instanceof DoorBlock;
			}

			@Override
			public boolean stand(int x, int y, int z) {
				if (!open(x, y, z) || !open(x, y + 1, z)) return false;
				BlockPos below = new BlockPos(x, y - 1, z);
				BlockState st = level.getBlockState(below);
				var shape = st.getCollisionShape(level, below);
				return !shape.isEmpty() && shape.max(net.minecraft.core.Direction.Axis.Y) <= 1.0 && !(st.getBlock() instanceof DoorBlock);
			}
		};
	}

	static int standY(GridPath.Terrain t, int x, int y, int z) {
		for (int yy = y + 3; yy >= y - 6; yy--) {
			if (t.stand(x, yy, z)) return yy;
		}
		return Integer.MIN_VALUE;
	}
}
