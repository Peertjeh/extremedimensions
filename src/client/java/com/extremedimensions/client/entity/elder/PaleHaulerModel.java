package com.extremedimensions.client.entity.elder;

import com.extremedimensions.ExtremeDimensions;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.util.Mth;

/**
 * The Pale Hauler moving (after its concept sheet). It stands a little hunched and breathes slowly, its head following
 * its prey, every strip of its mantle and the tail of its hood swaying on its own, its long fingers flexing. It walks
 * in long strides, its arms swinging low and long and its strips trailing and bouncing. Closing in it goes a little
 * lower. Hauling a block out of a bridge it crouches over it, both hands forward and down on it, palms in and fingers
 * curled over it, and heaves at it again and again, shaking with the strain, its strips swinging forward. Before a leap
 * it folds down low, arms drawn back and out with the claws spread, quivering; in the air it is thrown forward with its
 * arms reaching out ahead, its legs trailing and its strips streaming out behind. With a block it took riding on it, it
 * holds it up over its head; about to step away into nothing it draws its arms up before its face and glances back.
 *
 * <p>The strips of its mantle, those over its shoulders and those hanging from its hood are kept hanging plumb however
 * its spine, arms and head turn. The geometry and its texture are generated by {@code tools/elders/pale_hauler.py}.
 */
public class PaleHaulerModel extends EntityModel<PaleHaulerRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(ExtremeDimensions.id("pale_hauler"), "main");

	/** How far its knees bend at rest, and the length of a thigh and of a shin (as pale_hauler.py builds them). */
	private static final float KNEE = 0.2F;
	private static final float LEG = 10.75F;

	private final ModelPart body, belly, chest, head, hood;
	private final ModelPart[] thigh = new ModelPart[2], shin = new ModelPart[2], foot = new ModelPart[2];
	private final ModelPart[] arm = new ModelPart[2], fore = new ModelPart[2], hand = new ModelPart[2];
	private final ModelPart[][] finger = new ModelPart[2][4], claw = new ModelPart[2][4];
	private final ModelPart[] peak, strips, sleeves, fringe, fine;
	/** Whether each strip hangs behind (1) or in front (0), and how far to its left (+) or right (-) it hangs (0..1). */
	private final float[] behind, aside;
	/** How each arm hangs at rest, and how far it has turned from that this frame (for the strips over its shoulder). */
	private final float[] armRestX = new float[2], armRestZ = new float[2], armX = new float[2], armZ = new float[2];

	public PaleHaulerModel(ModelPart model) {
		super(model);
		this.body = PaleHaulerGeometry.find(model, "body");
		this.belly = PaleHaulerGeometry.find(model, "belly");
		this.chest = PaleHaulerGeometry.find(model, "chest");
		this.head = PaleHaulerGeometry.find(model, "head");
		this.hood = PaleHaulerGeometry.find(model, "hood");
		String[] sides = {"l", "r"};
		for (int i = 0; i < 2; i++) {
			String side = sides[i];
			thigh[i] = PaleHaulerGeometry.find(model, "thigh_" + side);
			shin[i] = PaleHaulerGeometry.find(model, "shin_" + side);
			foot[i] = PaleHaulerGeometry.find(model, "foot_" + side);
			arm[i] = PaleHaulerGeometry.find(model, "arm_" + side);
			fore[i] = PaleHaulerGeometry.find(model, "fore_" + side);
			hand[i] = PaleHaulerGeometry.find(model, "hand_" + side);
			armRestX[i] = arm[i].xRot;
			armRestZ[i] = arm[i].zRot;
			for (int j = 0; j < 4; j++) {
				finger[i][j] = PaleHaulerGeometry.find(model, "finger_" + side + j);
				claw[i][j] = PaleHaulerGeometry.find(model, "claw_" + side + j);
			}
		}
		this.peak = ElderAnim.parts(model, new String[] {"peak0", "peak1"}, PaleHaulerGeometry::find);
		this.strips = ElderAnim.parts(model, PaleHaulerGeometry.STRIP, PaleHaulerGeometry::find);
		this.sleeves = ElderAnim.parts(model, PaleHaulerGeometry.SLEEVE, PaleHaulerGeometry::find);
		this.fringe = ElderAnim.parts(model, PaleHaulerGeometry.FRINGE, PaleHaulerGeometry::find);
		this.fine = ElderAnim.parts(model, PaleHaulerGeometry.FINE, PaleHaulerGeometry::find);
		// (read from where each strip hangs at rest)
		this.behind = new float[strips.length];
		this.aside = new float[strips.length];
		for (int i = 0; i < strips.length; i++) {
			behind[i] = strips[i].z > 0 ? 1 : 0;
			aside[i] = Mth.clamp(strips[i].x / 7.0F, -1.0F, 1.0F);
		}
	}

	@Override
	public void setupAnim(PaleHaulerRenderState s) {
		super.setupAnim(s);
		// Its eyes are fine parts, built four times larger for their white-hot cores
		for (ModelPart f : fine) {
			f.xScale = PaleHaulerGeometry.FINE_SCALE;
			f.yScale = PaleHaulerGeometry.FINE_SCALE;
			f.zScale = PaleHaulerGeometry.FINE_SCALE;
		}
		float t = s.ageInTicks;
		float stalk = s.stalk, haul = s.haul, crouch = s.crouch, leap = s.leap, carry = s.carry, flee = s.flee;
		float held = Math.max(haul, Math.max(crouch, leap));
		float ws = Math.min(1.0F, s.walkAnimationSpeed * 1.5F) * (1 - held);
		float wp = s.walkAnimationPos * 0.45F;
		float stride = Mth.cos(wp), sway = Mth.sin(wp);
		float breathe = Mth.sin(t * 0.07F);
		// Hauling it heaves back on the block again and again; hauling or crouched, it shakes with the strain
		float heave = haul * (0.5F + 0.5F * Mth.sin(t * 0.45F));
		float strain = ElderAnim.tremor(t, 0.012F * haul + 0.02F * crouch);

		// The spine: a slow breath, the hunch deepening as it closes in, bowed over a block it hauls, folded down before
		// a leap, thrown forward in the air, straighter with a block held up, curled in as it steps away
		float bodyX = 0.05F * stalk + 0.06F * ws + 0.32F * haul + 0.3F * crouch + 0.5F * leap + 0.05F * carry + 0.1F * flee;
		float bellyX = 0.02F * breathe + 0.15F * haul + 0.12F * crouch + 0.1F * leap;
		float chestX = 0.03F * breathe + 0.2F * haul + 0.15F * crouch + 0.05F * leap + 0.05F * carry + 0.15F * flee - 0.1F * heave + strain;
		float roll = 0.05F * sway * ws;
		body.xRot += bodyX;
		body.zRot += roll;
		belly.xRot += bellyX;
		chest.xRot += chestX;
		chest.yRot -= 0.08F * stride * ws;
		// how far the mantle (and all that hangs from it) has turned from level
		float lean = bodyX + bellyX + chestX;

		// Legs: long strides, the knee folding as the leg swings through. Crouched the hips go down and the knees bend
		// just so far that the feet stay on the ground; in the air the legs trail behind, folded
		float drop = 1.0F * stalk + 6.5F * haul + 7.0F * crouch;
		float span = 2 * LEG * Mth.cos(KNEE);
		float bend = (float) Math.acos(Mth.clamp((span - drop) / (2 * LEG), 0.3F, 1.0F)) - KNEE;
		float bob = 2.0F * ws * stride * stride;
		body.y += drop + bob;
		for (int i = 0; i < 2; i++) {
			float sd = i == 0 ? 1 : -1;
			float swing = sd * stride * 0.5F * ws;
			float knee = Math.max(0, sd * sway) * 0.8F * ws;
			float tx = Mth.lerp(leap, -bend + swing, 0.55F + 0.12F * sd);
			float sx = Mth.lerp(leap, 2 * bend + knee, 0.9F - 0.25F * sd);
			float fx = Mth.lerp(leap, -bend - 0.7F * (swing + knee), 0.45F);
			thigh[i].y += drop + bob;
			thigh[i].xRot += tx;
			thigh[i].zRot -= sd * 0.1F * crouch;
			shin[i].xRot += sx;
			foot[i].xRot += fx;
		}

		// Arms: they hang plumb from the shoulders however it leans, swinging low and long as it walks, the forearms
		// trailing. Its poses aim them in the model, however the spine is bent: hauling, both reach forward and down
		// onto the block, palms turned in, and heave at it; crouched to leap they draw back and out, claws hooked;
		// in the air they reach out ahead, fingers spread; holding a block up they go up and out, the forearms in over
		// its head; stepping away it draws them up before its face
		for (int i = 0; i < 2; i++) {
			float sd = i == 0 ? 1 : -1;
			arm[i].xRot += -lean - sd * stride * 0.32F * ws + 0.03F * Mth.sin(t * 0.06F + i * 1.7F);
			arm[i].zRot -= sd * 0.03F * breathe;
			fore[i].xRot += -0.12F * ws - 0.18F * ws * Math.max(0, sd * stride) + 0.03F * Mth.sin(t * 0.05F + i);
			point(arm[i], haul, 0.12F * sd + strain, 0.82F, -0.56F + 0.12F * heave, body, belly, chest);
			point(arm[i], crouch, 0.5F * sd, 0.82F, 0.28F, body, belly, chest);
			point(arm[i], leap, 0.28F * sd, -0.4F, -0.87F, body, belly, chest);
			point(arm[i], carry, 0.78F * sd, -0.6F, 0.12F, body, belly, chest);
			point(arm[i], flee, 0.05F * sd, 0.85F, -0.52F, body, belly, chest);
			point(fore[i], haul, 0.02F * sd, 0.55F + 0.1F * heave, -0.83F, body, belly, chest, arm[i]);
			point(fore[i], crouch, 0.3F * sd, 0.75F, -0.6F, body, belly, chest, arm[i]);
			point(fore[i], leap, 0.12F * sd, -0.25F, -0.96F, body, belly, chest, arm[i]);
			point(fore[i], carry, -0.88F * sd, -0.45F, -0.1F, body, belly, chest, arm[i]);
			point(fore[i], flee, -0.5F * sd, -0.45F, -0.75F, body, belly, chest, arm[i]);
			hand[i].xRot += 0.06F * Mth.sin(t * 0.05F + 1 + i) - 0.1F * haul - 0.3F * crouch - 0.2F * leap + 0.3F * flee;
			// hauling, the palms turn to face each other, on either side of the block
			hand[i].yRot += 0.45F * sd * haul;
			// holding a block up, the hands turn up along its sides
			hand[i].zRot -= 1.0F * sd * carry;
			float curl = 0.1F * haul + 0.25F * crouch - 0.3F * leap + 0.2F * carry + 0.35F * flee;
			float tip = 0.2F * haul + 0.45F * crouch - 0.2F * leap;
			for (int j = 0; j < 4; j++) {
				float flex = curl + 0.06F * Mth.sin(t * 0.06F + j * 0.9F + i * 2.0F);
				finger[i][j].zRot += sd * flex;
				claw[i][j].zRot += sd * (tip + 0.6F * flex);
			}
			armX[i] = arm[i].xRot - armRestX[i] + lean;
			armZ[i] = arm[i].zRot - armRestZ[i];
		}

		// Head: it follows its prey (or the block in its hands), held level however the spine leans, with a slow
		// curious tilt; it lifts to its prey before a leap, and glances back as it steps away
		float yaw = Mth.clamp(s.yRot, -75.0F, 75.0F) * Mth.DEG_TO_RAD;
		float pitch = Mth.clamp(s.xRot, -50.0F, 60.0F) * Mth.DEG_TO_RAD;
		float hx = pitch - lean + 0.035F * Mth.sin(t * 0.05F) - 0.12F * crouch - 0.2F * leap + 0.45F * carry + 0.12F * flee;
		head.yRot += Mth.lerp(flee, yaw, 0.7F * Mth.sin(t * 0.07F));
		head.xRot += hx;
		head.zRot += 0.07F * Mth.sin(t * 0.031F) * (1 - held) + strain;
		hood.xRot += 0.015F * Mth.sin(t * 0.07F + 1.0F);
		// how far the head has turned from level, for what hangs from it
		float nod = hx + lean;
		// The tail of its hood swings, and streams back in a leap
		peak[0].xRot += 0.08F * Mth.sin(t * 0.055F) + 0.1F * ws * Mth.sin(wp * 2) - 0.3F * leap;
		peak[0].zRot += 0.06F * Mth.sin(t * 0.045F + 1.0F);
		peak[1].xRot += 0.1F * Mth.sin(t * 0.055F - 0.7F) - 0.2F * leap;

		// The strips hang plumb from the mantle however it leans, each swaying on its own; walking they trail back and
		// bounce with each stride (those in front less, so they keep off the legs); hauling they swing forward over the
		// block; crouched they quiver; in the air they stream out behind, the side ones flaring out
		for (int i = 0; i < strips.length; i++) {
			float ph = i * 1.37F;
			float back = 0.45F + 0.55F * behind[i];
			strips[i].xRot += -lean + 0.05F * Mth.sin(t * 0.06F + ph) + ws * back * (0.25F + 0.08F * Mth.sin(wp * 2 + ph))
					- 0.25F * haul * (0.8F + 0.2F * Mth.sin(t * 0.45F + ph)) + 0.04F * crouch * Mth.sin(t * 1.3F + ph)
					+ leap * back * (1.1F + 0.15F * Mth.sin(t * 0.9F + ph));
			strips[i].zRot += -roll + 0.04F * Mth.cos(t * 0.05F + ph * 0.7F) - aside[i] * 0.35F * leap;
		}
		for (int i = 0; i < sleeves.length; i++) {
			int side = i * 2 / sleeves.length;
			float ph = i * 2.1F + 0.5F;
			sleeves[i].xRot += -armX[side] + 0.05F * Mth.sin(t * 0.06F + ph) + 0.2F * ws + 0.8F * leap;
			sleeves[i].zRot += -armZ[side] - roll + 0.04F * Mth.cos(t * 0.05F + ph);
		}
		for (int i = 0; i < fringe.length; i++) {
			float ph = i * 1.9F + 1.0F;
			fringe[i].xRot += -nod + 0.06F * Mth.sin(t * 0.07F + ph) + 0.15F * ws + 0.6F * leap;
			fringe[i].zRot += 0.05F * Mth.cos(t * 0.06F + ph);
		}
	}

	/**
	 * Turns a limb by {@code k} of the way from where it is to point along (x, y, z) of the model, whatever the parts it
	 * hangs from ({@code chain}, from the root down) are doing. Of the two ways to turn it there (raised over the front,
	 * or round by the side), it takes the one nearer how it is turned already, so it swings there the short way.
	 */
	private static void point(ModelPart limb, float k, float x, float y, float z, ModelPart... chain) {
		if (k < 0.001F) {
			return;
		}
		float[] d = ElderAnim.aim(x, y, z, chain);
		float x1 = (float) Math.asin(Mth.clamp(d[2], -1.0F, 1.0F)), z1 = (float) Math.atan2(-d[0], d[1]);
		float x2 = ElderAnim.wrap(Mth.PI - x1), z2 = (float) Math.atan2(d[0], -d[1]);
		float dx1 = ElderAnim.wrap(x1 - limb.xRot), dz1 = ElderAnim.wrap(z1 - limb.zRot);
		float dx2 = ElderAnim.wrap(x2 - limb.xRot), dz2 = ElderAnim.wrap(z2 - limb.zRot);
		boolean over = Math.abs(dx2) + Math.abs(dz2) < Math.abs(dx1) + Math.abs(dz1);
		limb.xRot += k * (over ? dx2 : dx1);
		limb.yRot -= k * limb.yRot;
		limb.zRot += k * (over ? dz2 : dz1);
	}
}
